#!/usr/bin/env python3
"""Export the per-case outcomes of every AgentDojo run to CSV, plus a summary table.

The raw run directories (results/<label>/<pipeline>/<suite>/<user task>/...) hold
full transcripts and are too large to publish. This writes, per arm, the fields
the paper's metrics need, so every number in the evaluation can be recomputed
from results-summary/ alone:

  <label>.benign.csv : suite,user_task,utility
  <label>.attack.csv : suite,user_task,injection_task,in_909,utility,security,security_as_logged

`security` follows aggregate.py: slack injection_task_5 is scored from the calls
that actually executed, and `security_as_logged` keeps AgentDojo's own value.
`in_909` is false for the two travel injection tasks Progent's vendored suite
drops; the paper reports the 909 cases with in_909 true.

Run from the repository root:
  python3 experiments/export_cases.py            # results/ and baselines/CaMeL/logs
  python3 experiments/export_cases.py results/guard4
"""
import csv, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from aggregate import DROPPED, arms, collect, wilson  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results-summary"
SKIP = {"smoke", "snapshot-check"}   # a smoke test and a model-snapshot check, not arms of the evaluation


def export(name: str, arm: Path) -> dict | None:
    benign, cases = collect(arm)
    if not benign and not cases:
        return None
    cases_dir = OUT / "cases"
    cases_dir.mkdir(parents=True, exist_ok=True)
    if benign:
        rows = sorted((d["suite_name"], d["user_task_id"], bool(d["utility"])) for d in benign)
        with (cases_dir / f"{name}.benign.csv").open("w", newline="") as f:
            w = csv.writer(f); w.writerow(["suite", "user_task", "utility"]); w.writerows(rows)
    if cases:
        rows = sorted((d["suite_name"], d["user_task_id"], d["injection_task_id"],
                       (d["suite_name"], d["injection_task_id"]) not in DROPPED,
                       bool(d["utility"]), bool(d.get("security")),
                       bool(d.get("security_as_logged", d.get("security")))) for d in cases)
        with (cases_dir / f"{name}.attack.csv").open("w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["suite", "user_task", "injection_task", "in_909", "utility", "security", "security_as_logged"])
            w.writerows(rows)
    kept = [d for d in cases if (d["suite_name"], d["injection_task_id"]) not in DROPPED]
    return {
        "arm": name, "pipeline": arm.name,
        "bu": (sum(bool(d["utility"]) for d in benign), len(benign)),
        "uua": (sum(bool(d["utility"]) for d in kept), len(kept)),
        "asr": (sum(bool(d.get("security")) for d in kept), len(kept)),
    }


def pct(k: int, n: int) -> str:
    if n == 0:
        return "-"
    lo, hi = wilson(k, n)
    return f"{100 * k / n:.2f} [{lo:.1f}, {hi:.1f}] ({k}/{n})"


def main(argv: list[str]) -> None:
    roots = [Path(a) for a in argv] or [ROOT / "results", ROOT / "baselines/CaMeL/logs"]
    summary = []
    for root in roots:
        if not root.is_dir():
            continue
        if root.name == "logs" and root.parent.name == "CaMeL":
            for arm in arms(root):                         # CaMeL: one pipeline per directory
                r = export(f"camel:{arm.name}", arm)
                if r: summary.append(r)
            continue
        labels = [root] if any((root / s).is_dir() for s in ("workspace", "slack", "travel", "banking")) \
            or any(x.is_dir() and any((x / s).is_dir() for s in ("workspace", "slack", "travel", "banking"))
                   for x in root.iterdir()) else sorted(x for x in root.iterdir() if x.is_dir())
        for label in labels:
            if label.name in SKIP:
                continue
            for arm in arms(label):
                name = label.name if arm.parent == label else f"{label.name}:{arm.name}"
                r = export(name, arm)
                if r: summary.append(r)
    OUT.mkdir(exist_ok=True)
    with (OUT / "summary.md").open("w") as f:
        f.write("# Per-arm metrics recomputed from results-summary/cases\n\n")
        f.write("Percent, Wilson 95% interval over cases, and k/n. BU over the 97 user tasks; "
                "UUA and ASR over the 909 security cases (`in_909`). Generated by experiments/export_cases.py.\n\n")
        f.write("| Arm | Pipeline | Benign utility | Utility under attack | Targeted ASR |\n|---|---|---|---|---|\n")
        for r in sorted(summary, key=lambda r: r["arm"]):
            f.write(f"| {r['arm']} | {r['pipeline']} | {pct(*r['bu'])} | {pct(*r['uua'])} | {pct(*r['asr'])} |\n")
    print(f"{len(summary)} arms -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1:])
